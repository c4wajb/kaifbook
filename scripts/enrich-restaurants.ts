async function main() {
  // 1. Delete demo restaurants
  console.log("Deleting demo restaurants...");
  for (const slug of ["red-stone-demo", "leto-demo-kursk"]) {
    const r = await prisma.restaurant.findFirst({ where: { slug } });
    if (r) {
      await prisma.restaurant.delete({ where: { id: r.id } });
      console.log(`  Deleted: ${slug}`);
    }
  }

  // 2. Update coordinates for all restaurants
  console.log("\nUpdating coordinates...");
  for (const [slug, coords] of Object.entries(coordinates)) {
    const result = await prisma.restaurant.updateMany({
      where: { slug },
      data: { latitude: coords.lat, longitude: coords.lon },
    });
    if (result.count > 0) console.log(`  ${slug}: coordinates set`);
  }

  // 3. Enrich menus
  console.log("\nEnriching menus...");
  for (const [slug, categories] of Object.entries(menus)) {
    const restaurant = await prisma.restaurant.findFirst({ where: { slug } });
    if (!restaurant) {
      console.log(`  ${slug}: not found, skipping`);
      continue;
    }

    // Delete existing menu data
    await prisma.menuItem.deleteMany({ where: { restaurantId: restaurant.id } });
    await prisma.menuCategory.deleteMany({ where: { restaurantId: restaurant.id } });

    // Create new categories and items
    for (let i = 0; i < categories.length; i++) {
      const cat = categories[i];
      const category = await prisma.menuCategory.create({
        data: {
          restaurantId: restaurant.id,
          title: cat.title,
          sortOrder: i,
          isActive: true,
        },
      });

      for (let j = 0; j < cat.items.length; j++) {
        const item = cat.items[j];
        await prisma.menuItem.create({
          data: {
            restaurantId: restaurant.id,
            categoryId: category.id,
            title: item.title,
            description: item.description,
            price: item.price,
            weight: item.weight,
            isAvailable: true,
            sortOrder: j,
          },
        });
      }
    }

    const totalItems = categories.reduce((sum, cat) => sum + cat.items.length, 0);
    console.log(`  ${slug}: ${categories.length} categories, ${totalItems} items`);
  }

  console.log("\nDone!");
}

main().finally(() => prisma.$disconnect());
